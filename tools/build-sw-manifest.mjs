import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const runtimeRoots = ['src', 'styles', 'assets'];
const rootRuntimeFiles = ['index.html', 'manifest.webmanifest', 'favicon.ico'];
const runtimeExtensions = new Set(['.html', '.css', '.js', '.json', '.svg', '.png', '.ico', '.webmanifest', '.mp3', '.ogg', '.wav']);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (entry.isFile() && runtimeExtensions.has(extname(entry.name))) files.push(path);
  }
  return files;
}

const files = [];
for (const directory of runtimeRoots) files.push(...await walk(join(root, directory)));
for (const file of rootRuntimeFiles) {
  try {
    await readFile(join(root, file));
    files.push(join(root, file));
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

const entries = [...new Map(files.map((file) => [
  `/${relative(root, file).split(sep).join('/')}`,
  file,
])).entries()].sort(([left], [right]) => left.localeCompare(right));
if (entries.length === 0) throw new Error('No runtime assets found for the service worker.');
const urls = entries.map(([url]) => url);
const hash = createHash('sha256');
for (const [url, file] of entries) {
  hash.update(url).update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 16);
const output = `// Generated by tools/build-sw-manifest.mjs.\nself.SW_ASSETS = ${JSON.stringify(urls, null, 2)};\nself.SW_VERSION = ${JSON.stringify(version)};\n`;
await writeFile(join(root, 'sw-assets.js'), output);
console.log(`Generated sw-assets.js (${urls.length} assets, ${version}).`);
